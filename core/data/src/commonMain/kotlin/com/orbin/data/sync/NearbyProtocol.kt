internal fun validateNearbyDocument(document: SyncDocument) {
    require(document.version == SYNC_FORMAT_VERSION) { "Update Orbin on both devices before syncing" }
    require(document.visits.size + document.bookmarks.size <= MAX_ACTIVITY_RECORDS) {
        "Too much activity for one nearby sync"
    }
    require(
        document.visits
            .map { it.key }
            .distinct()
            .size == document.visits.size,
    ) { "Duplicate thread visits" }
    require(
        document.bookmarks
            .map { it.key }
            .distinct()
            .size == document.bookmarks.size,
    ) { "Duplicate bookmarks" }
    val keys = document.visits.map { it.key } + document.bookmarks.map { it.key }
    require(
        keys.all { it.provider.isNotBlank() && it.board.isNotBlank() && it.thread > 0 },
    ) { "Invalid thread identity" }
}

