internal val NEARBY_PORT_RANGE = 1024..65535
internal const val MAX_NEARBY_CODE_LENGTH = 2048
private const val MAX_ACTIVITY_RECORDS = 50_000
private const val TOKEN_BYTES = 32
private val TOKEN_LENGTH = 43..44
internal const val NEARBY_PORT = 39157
internal const val MAX_NEARBY_BYTES = 8 * 1024 * 1024
internal const val INVITE_LIFETIME_MS = 10 * 60 * 1000L
internal const val MAX_NEARBY_DEVICES = 8
internal val NearbyJson = Json { ignoreUnknownKeys = true }

/**
 * What a pairing code (and its QR code) carries. [host] is the inviter's local IPv4 address, or null
 * when it has no local network; [bluetooth] says the inviter also accepts the invitation over
 * Bluetooth LE, found by the beacon derived from [id]. At least one route is always present.
 */
@Serializable
internal data class NearbyInvite(
    val id: String,
    val secret: String,
    val host: String?,
    val port: Int,
    val expires: Long,
    val bluetooth: Boolean = false,
    /** The inviter's relay server, so a joiner anywhere on the Internet can meet it there. */
    val relay: String? = null,
) {
    fun code(): String = "orbin-nearby1:" + Base64.UrlSafe.encode(NearbyJson.encodeToString(this).encodeToByteArray())

    companion object {
        fun parse(code: String): NearbyInvite {
            require(code.length <= MAX_NEARBY_CODE_LENGTH && code.startsWith("orbin-nearby1:")) {
                "Use an Orbin nearby pairing code"
            }
            val invite =
                NearbyJson.decodeFromString<NearbyInvite>(
                    Base64.UrlSafe.decode(code.removePrefix("orbin-nearby1:")).decodeToString(),
                )
            require(
                (invite.host == null || localAddress(invite.host)) && invite.port in NEARBY_PORT_RANGE,
            ) { "Pairing requires a local network address" }
            require(invite.relay == null || normalizeRelayUrl(invite.relay) == invite.relay) { "Invalid relay address" }
            require(invite.host != null || invite.bluetooth || invite.relay != null) {
                "Pairing code has no way to reach the device"
            }
            require(validToken(invite.id) && validToken(invite.secret)) { "Invalid pairing code" }
            return invite
        }
    }
}

/** Numeric local IPv4 only: pairing never performs DNS or connects to an Internet address. */
@Suppress("MagicNumber") // Literal IPv4 octets make the standard private ranges auditable.
internal fun localAddress(host: String): Boolean {
    val parts = host.split('.')
    if (parts.size != 4 || parts.any { it.isEmpty() || it.any { c -> c !in '0'..'9' } }) return false
    val octets = parts.map { it.toIntOrNull() ?: return false }
    if (octets.any { it !in 0..255 } || octets.map { it.toString() } != parts) return false
    return octets[0] == 10 ||
        octets[0] == 127 ||
        (octets[0] == 172 && octets[1] in 16..31) ||
        (octets[0] == 192 && octets[1] == 168) ||
        (octets[0] == 169 && octets[1] == 254)
}

internal fun validToken(value: String): Boolean =
    value.length in TOKEN_LENGTH && runCatching { Base64.UrlSafe.decode(value).size == TOKEN_BYTES }.getOrDefault(false)

/** AEAD comes from the platform provider; fresh IVs are generated by the library for every frame. */
internal object NearbyCrypto {
    suspend fun token(): String =
        Base64.UrlSafe.encode(
            CryptographyProvider.Default
                .get(AES.GCM)
                .keyGenerator(AES.Key.Size.B256)
                .generateKey()
                .encodeToByteArray(AES.Key.Format.RAW),
        )

    suspend fun encrypt(
        secret: String,
        context: String,
        plaintext: ByteArray,
    ): ByteArray = key(secret).cipher().encrypt(plaintext, context.encodeToByteArray())

    suspend fun decrypt(
        secret: String,
        context: String,
        ciphertext: ByteArray,
    ): ByteArray = key(secret).cipher().decrypt(ciphertext, context.encodeToByteArray())

    private suspend fun key(secret: String): AES.GCM.Key {
        require(validToken(secret)) { "Invalid device key" }
        return CryptographyProvider.Default
            .get(AES.GCM)
            .keyDecoder()
            .decodeFromByteArray(AES.Key.Format.RAW, Base64.UrlSafe.decode(secret))
    }
}

